/**
 * Article Reader Controller
 */
function initArticleReader() {
  const readerOverlay = document.getElementById('article-fullpage-reader');
  if (!readerOverlay) return;

  const closeBtn = document.getElementById('article-reader-close');
  const backBtn = document.getElementById('article-reader-back-btn');
  const shareBtn = document.getElementById('article-reader-share-btn');
  const progressBar = document.getElementById('article-reading-progress');

  // Close reader
  function closeReader(updateHistory = true) {
    readerOverlay.classList.add('hidden');
    document.body.style.overflow = '';
    document.title = "Love'N'People | 501(c)(3) Nonprofit Uplifting Northeast TN & Southwest VA Since 2012";
    if (updateHistory && window.location.hash.startsWith('#article/')) {
      history.pushState(null, '', window.location.pathname + window.location.search);
    }
  }

  // Open reader for article ID
  function openReader(articleId, updateHistory = true) {
    const article = loveNPeopleArticles[articleId];
    if (!article) return;

    // Populate data
    document.getElementById('article-reader-badge').textContent = article.category;
    document.getElementById('article-reader-date').textContent = `${article.date} • ${article.readTime}`;
    document.getElementById('article-reader-title').textContent = article.title;
    document.getElementById('article-reader-subtitle').textContent = article.subtitle;
    document.getElementById('article-reader-author').textContent = `By ${article.author}`;

    // Cover Image
    const coverEl = document.getElementById('article-reader-cover');
    coverEl.src = article.coverImage;
    coverEl.alt = article.coverAlt || article.title;

    // Summary Box
    document.getElementById('article-reader-summary').textContent = article.summary;

    // Highlights List
    const highlightsEl = document.getElementById('article-reader-highlights');
    highlightsEl.innerHTML = '';
    article.highlights.forEach(h => {
      const li = document.createElement('li');
      li.className = 'flex items-start space-x-2 text-xs sm:text-sm text-slate-700';
      li.innerHTML = `<span class="text-rose-600 font-bold mt-0.5">•</span><span>${h}</span>`;
      highlightsEl.appendChild(li);
    });

    // Content Paragraphs
    const bodyEl = document.getElementById('article-reader-body');
    bodyEl.innerHTML = '';
    article.content.forEach(sec => {
      const secDiv = document.createElement('div');
      secDiv.className = 'space-y-2';
      secDiv.innerHTML = `
        <h3 class="text-lg sm:text-xl font-bold text-slate-900 tracking-tight">${sec.heading}</h3>
        <p class="text-slate-600 text-sm sm:text-base leading-relaxed">${sec.text}</p>
      `;
      bodyEl.appendChild(secDiv);
    });

    // Gallery
    const galleryContainer = document.getElementById('article-reader-gallery-container');
    const galleryGrid = document.getElementById('article-reader-gallery');
    if (article.gallery && article.gallery.length > 0) {
      galleryContainer.classList.remove('hidden');
      galleryGrid.innerHTML = '';
      article.gallery.forEach(g => {
        const item = document.createElement('div');
        item.className = 'rounded-2xl overflow-hidden border border-slate-200/90 shadow-sm bg-slate-100 group';
        item.innerHTML = `
          <div class="aspect-[4/3] overflow-hidden">
            <img src="${g.src}" alt="${g.caption}" class="w-full h-full object-cover group-hover:scale-105 transition-transform duration-300" loading="lazy" />
          </div>
          <p class="p-2 text-[11px] text-slate-500 font-medium text-center bg-white">${g.caption}</p>
        `;
        galleryGrid.appendChild(item);
      });
    } else {
      galleryContainer.classList.add('hidden');
    }

    // CTA Button
    const ctaBtn = document.getElementById('article-reader-cta');
    ctaBtn.textContent = article.cta.label;
    ctaBtn.href = article.cta.href;
    if (article.cta.href.startsWith('http')) {
      ctaBtn.target = '_blank';
      ctaBtn.rel = 'noopener noreferrer';
    } else {
      ctaBtn.removeAttribute('target');
      ctaBtn.removeAttribute('rel');
      ctaBtn.onclick = () => closeReader(true);
    }
    document.getElementById('article-reader-cta-secondary').textContent = article.cta.secondaryText;

    // Related Articles
    const relatedGrid = document.getElementById('article-reader-related');
    relatedGrid.innerHTML = '';
    const otherIds = Object.keys(loveNPeopleArticles).filter(id => id !== articleId).slice(0, 3);
    otherIds.forEach(otherId => {
      const other = loveNPeopleArticles[otherId];
      const card = document.createElement('div');
      card.className = 'apple-mesh-card bg-white rounded-2xl p-4 border border-slate-200/80 shadow-sm hover:shadow-md cursor-pointer transition';
      card.onclick = () => {
        openReader(otherId, true);
        readerOverlay.scrollTo({ top: 0, behavior: 'smooth' });
      };
      card.innerHTML = `
        <span class="text-[10px] font-bold uppercase tracking-wider text-rose-600 block mb-1">${other.category}</span>
        <h4 class="text-xs sm:text-sm font-bold text-slate-900 line-clamp-2 mb-2">${other.title}</h4>
        <span class="text-[11px] font-semibold text-rose-600 flex items-center">Read Story &rarr;</span>
      `;
      relatedGrid.appendChild(card);
    });

    // Reveal overlay
    readerOverlay.classList.remove('hidden');
    document.body.style.overflow = 'hidden';
    readerOverlay.scrollTop = 0;
    document.title = `${article.title} | Love'N'People`;

    if (updateHistory) {
      history.pushState({ articleId }, '', `#article/${articleId}`);
    }

    if (window.lucide) {
      window.lucide.createIcons();
    }
  }

  // Scroll listener for reading progress bar
  readerOverlay.addEventListener('scroll', () => {
    const total = readerOverlay.scrollHeight - readerOverlay.clientHeight;
    if (total > 0) {
      const pct = Math.min(100, Math.round((readerOverlay.scrollTop / total) * 100));
      if (progressBar) progressBar.style.width = `${pct}%`;
    }
  });

  // Event Listeners
  if (closeBtn) closeBtn.onclick = () => closeReader(true);
  if (backBtn) backBtn.onclick = () => closeReader(true);

  // ESC key to close
  window.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && !readerOverlay.classList.contains('hidden')) {
      closeReader(true);
    }
  });

  // Popstate for browser back button
  window.addEventListener('popstate', () => {
    if (window.location.hash.startsWith('#article/')) {
      const slug = window.location.hash.replace('#article/', '');
      openReader(slug, false);
    } else {
      closeReader(false);
    }
  });

  // Native Web Share or Copy Link
  if (shareBtn) {
    shareBtn.onclick = async () => {
      const url = window.location.href;
      const title = document.getElementById('article-reader-title').textContent;
      if (navigator.share) {
        try {
          await navigator.share({ title, url });
        } catch (err) {
          // ignore abort
        }
      } else {
        try {
          await navigator.clipboard.writeText(url);
          const orig = shareBtn.innerHTML;
          shareBtn.innerHTML = '<span class="text-xs font-bold text-emerald-600">Copied!</span>';
          setTimeout(() => shareBtn.innerHTML = orig, 2000);
        } catch (e) {
          alert("Article URL copied to clipboard: " + url);
        }
      }
    };
  }

  // Delegate clicks on all elements with data-article-target
  document.addEventListener('click', (e) => {
    const trigger = e.target.closest('[data-article-target]');
    if (trigger) {
      e.preventDefault();
      const targetId = trigger.getAttribute('data-article-target');
      openReader(targetId, true);
    }
  });

  // Check URL on load
  if (window.location.hash.startsWith('#article/')) {
    const slug = window.location.hash.replace('#article/', '');
    openReader(slug, false);
  }

  // Expose to window
  window.loveNPeopleArticles = loveNPeopleArticles;
  window.openLoveNPeopleArticle = openReader;
  window.closeLoveNPeopleArticle = closeReader;
}

// Auto-initialize when DOM is ready
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initArticleReader);
} else {
  initArticleReader();
}
